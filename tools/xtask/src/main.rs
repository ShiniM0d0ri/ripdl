//! Repository chores. Run `cargo run -p xtask -- protocol` to regenerate the
//! TypeScript bindings, or `--check` in CI to fail when they are stale.

use anyhow::{bail, Context, Result};
use ripdl_core::links::LinkSnapshot;
use ripdl_core::traffic::{ControllerSnapshot, TaskTrafficSnapshot, TrafficKind, TrafficState};
use ts_rs::{Config, TS};

const HEADER: &str = "// Generated by `cargo run -p xtask -- protocol`. Do not edit.\n\n";
const TARGETS: &[&str] = &["ext/src/protocol.d.ts"];

fn generate() -> Result<String> {
    let cfg = Config::default();
    let mut out = String::from(HEADER);
    for decl in [
        TrafficKind::export_to_string(&cfg)?,
        TrafficState::export_to_string(&cfg)?,
        TaskTrafficSnapshot::export_to_string(&cfg)?,
        ControllerSnapshot::export_to_string(&cfg)?,
        LinkSnapshot::export_to_string(&cfg)?,
    ] {
        out.push_str(&decl);
        out.push('\n');
    }
    Ok(out)
}

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let check = args.iter().any(|a| a == "--check");
    let generated = generate().context("generating protocol types")?;

    for target in TARGETS {
        let path = std::path::Path::new(target);
        if check {
            let current = std::fs::read_to_string(path).with_context(|| {
                format!("reading {target} - run `cargo run -p xtask -- protocol`")
            })?;
            if current.replace("\r\n", "\n") != generated.replace("\r\n", "\n") {
                bail!("{target} is stale - run `cargo run -p xtask -- protocol`");
            }
        } else {
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent)?;
            }
            std::fs::write(path, &generated).with_context(|| format!("writing {target}"))?;
        }
    }
    if !check {
        println!("generated {}", TARGETS.join(", "));
    }
    Ok(())
}
