//! Install/uninstall user script plugins into the unpacked browser
//! extension's `hosts/local/` folder and keep its generated
//! `registry.js` in sync.
//!
//! The service worker statically imports `hosts/local/registry.js` because
//! dynamic `import()` is forbidden on `ServiceWorkerGlobalScope` - and a
//! stale registry (a file listed but missing, or present but unlisted) kills
//! background.js, which hangs every extension RPC. So the registry is always
//! regenerated from the files actually on disk and swapped atomically
//! (temp file + rename), never edited in place.

use std::path::Path;

/// The registry file this module owns - never treat it as a plugin.
const REGISTRY_JS: &str = "registry.js";
/// Kept in sync with the header the committed default carries.
const REGISTRY_HEADER: &str = r#"/**
 * User-loaded script plugin registry - GENERATED by ripdl's add-plugin tool,
 * one static import per script in hosts/local/. The service worker statically
 * imports this module because the HTML spec forbids dynamic import() on
 * ServiceWorkerGlobalScope (verified live: Chromium rejects it), and a failed
 * static import would kill background.js - so the tool keeps this file in
 * sync with the files actually present.
 *
 * Adding a script means: copy the .js here, add its namespace import + entry
 * below, reload the extension (the Plugins page prompts for that one click).
 */
"#;

/// Install (or upgrade) one script plugin: copy the file into
/// `<ext>/hosts/local/`, regenerate `registry.js`, return the installed
/// file name. The source name must be a plain `.js` file name - the caller
/// hands over user input, so this re-checks rather than trusting it.
pub fn install(ext_dir: &Path, source_name: &str, content: &[u8]) -> Result<String, String> {
    let name = plugin_file_name(source_name)?;
    if content.is_empty() {
        return Err("the plugin file is empty".into());
    }
    let local = ext_dir.join("hosts").join("local");
    std::fs::create_dir_all(&local).map_err(|e| format!("{}: {e}", local.display()))?;
    let target = local.join(&name);
    crate::util::atomic_write(&target, content)
        .map_err(|e| format!("{}: {e}", target.display()))?;
    let scripts = regenerate(&local)?;
    Ok(format!("{name} (registry now lists {})", scripts.len()))
}

/// Remove one script plugin and regenerate the registry. `registry.js`
/// itself is not a plugin; refusing it here keeps the tool from deleting
/// the file it is supposed to rewrite.
pub fn uninstall(ext_dir: &Path, filename: &str) -> Result<(), String> {
    let name = plugin_file_name(filename)?;
    let local = ext_dir.join("hosts").join("local");
    let target = local.join(&name);
    std::fs::remove_file(&target).map_err(|e| format!("{}: {e}", target.display()))?;
    regenerate(&local)?;
    Ok(())
}

/// The scripts `registry.js` currently lists (files on disk, sorted).
pub fn installed(ext_dir: &Path) -> Vec<String> {
    let local = ext_dir.join("hosts").join("local");
    list_scripts(&local).unwrap_or_default()
}

/// Re-list every script in `hosts/local/` in `registry.js`. The installer
/// runs this after an upgrade: the shipped registry lists only the defaults,
/// so the user's scripts are copied back first and then re-listed here. The
/// folder must hold a `manifest.json`, which keeps a wrong path from creating
/// a stray `hosts/local/` tree somewhere else.
pub fn sync(ext_dir: &Path) -> Result<Vec<String>, String> {
    if !ext_dir.join("manifest.json").is_file() {
        return Err(format!(
            "{} has no manifest.json - not an unpacked extension folder",
            ext_dir.display()
        ));
    }
    let local = ext_dir.join("hosts").join("local");
    std::fs::create_dir_all(&local).map_err(|e| format!("{}: {e}", local.display()))?;
    regenerate(&local)
}

/// Copy a newer bundled extension into its per-user managed folder. The
/// staging directory keeps the previous extension intact until the new tree
/// is complete; local scripts are overlaid before the generated registry is
/// rebuilt.
pub fn sync_managed(source: &Path, managed: &Path) -> Result<ManagedCopy, String> {
    let source_version = folder_version(source)
        .ok_or_else(|| format!("{} has no readable manifest version", source.display()))?;
    let managed_version = folder_version(managed);
    let version_order = managed_version
        .as_deref()
        .map(|current| crate::update::compare_versions(&source_version, current));
    let update = version_order.is_none_or(|order| {
        order.is_gt() || (cfg!(debug_assertions) && order.is_eq())
    });

    if update {
        let nonce = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap_or_default()
            .as_nanos();
        let parent = managed.parent().unwrap_or_else(|| Path::new("."));
        std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
        let stage = parent.join(format!("extension-stage-{}-{nonce}", std::process::id()));
        let backup = parent.join(format!("extension-backup-{}-{nonce}", std::process::id()));
        let _ = std::fs::remove_dir_all(&stage);
        let prepare = (|| {
            copy_tree(source, &stage)?;

            let old_local = managed.join("hosts").join("local");
            let new_local = stage.join("hosts").join("local");
            std::fs::create_dir_all(&new_local)
                .map_err(|e| format!("{}: {e}", new_local.display()))?;
            if old_local.is_dir() {
                for entry in std::fs::read_dir(&old_local)
                    .map_err(|e| format!("{}: {e}", old_local.display()))?
                {
                    let entry = entry.map_err(|e| e.to_string())?;
                    let name = entry.file_name();
                    let name_str = name.to_string_lossy();
                    if name_str.to_ascii_lowercase().ends_with(".js")
                        && !name_str.eq_ignore_ascii_case(REGISTRY_JS)
                        && entry.path().is_file()
                    {
                        std::fs::copy(entry.path(), new_local.join(name))
                            .map_err(|e| format!("{}: {e}", entry.path().display()))?;
                    }
                }
            }
            sync(&stage)?;
            Ok::<(), String>(())
        })();
        if let Err(e) = prepare {
            let _ = std::fs::remove_dir_all(&stage);
            return Err(e);
        }

        let had_managed = managed.exists();
        if had_managed {
            if let Err(e) = std::fs::rename(managed, &backup) {
                let _ = std::fs::remove_dir_all(&stage);
                return Err(format!("cannot stage old extension {}: {e}", managed.display()));
            }
        }
        if let Err(e) = std::fs::rename(&stage, managed) {
            if had_managed {
                let _ = std::fs::rename(&backup, managed);
            }
            let _ = std::fs::remove_dir_all(&stage);
            return Err(format!("cannot activate managed extension {}: {e}", managed.display()));
        }
        if had_managed {
            let _ = std::fs::remove_dir_all(&backup);
        }
    } else {
        sync(managed)?;
    }

    let version = folder_version(managed)
        .ok_or_else(|| format!("{} has no readable manifest version", managed.display()))?;
    Ok(ManagedCopy {
        source_version,
        version,
        updated: update,
        plugins: installed(managed),
    })
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ManagedCopy {
    pub source_version: String,
    pub version: String,
    pub updated: bool,
    pub plugins: Vec<String>,
}

fn copy_tree(source: &Path, destination: &Path) -> Result<(), String> {
    std::fs::create_dir_all(destination)
        .map_err(|e| format!("{}: {e}", destination.display()))?;
    for entry in std::fs::read_dir(source).map_err(|e| format!("{}: {e}", source.display()))? {
        let entry = entry.map_err(|e| e.to_string())?;
        let from = entry.path();
        let to = destination.join(entry.file_name());
        let kind = entry
            .file_type()
            .map_err(|e| format!("{}: {e}", from.display()))?;
        if kind.is_dir() {
            copy_tree(&from, &to)?;
        } else if kind.is_file() {
            std::fs::copy(&from, &to).map_err(|e| format!("{}: {e}", from.display()))?;
        } else {
            return Err(format!("unsupported bundled extension entry: {}", from.display()));
        }
    }
    Ok(())
}

/// The `version` from an extension folder's `manifest.json`, or `None` when
/// there is no readable manifest. The file is JSONC (full-line `//` comments,
/// as the release CI also reads it), so those lines are dropped first.
pub fn folder_version(ext_dir: &Path) -> Option<String> {
    let src = std::fs::read_to_string(ext_dir.join("manifest.json")).ok()?;
    let json: String = src
        .lines()
        .filter(|line| !line.trim_start().starts_with("//"))
        .collect::<Vec<_>>()
        .join("\n");
    let value: serde_json::Value = serde_json::from_str(&json).ok()?;
    value.get("version")?.as_str().map(str::to_string)
}

/// A plugin file name: one path component, ends in `.js`, not the registry
/// itself. Returns the sanitized name to install under.
fn plugin_file_name(source: &str) -> Result<String, String> {
    let raw = source.trim();
    if raw.is_empty() {
        return Err("no plugin file name".into());
    }
    // Windows or Unix separators both split: the plugin lands in the
    // extension's own folder, never wherever the path points.
    let base = raw.rsplit(['/', '\\']).next().unwrap_or(raw);
    if base != raw.trim() && base.is_empty() {
        return Err(format!("not a plugin file name: {raw:?}"));
    }
    let name = crate::names::sanitize_component(base, "plugin");
    if !name.to_ascii_lowercase().ends_with(".js") {
        return Err(format!("{base} is not a .js script (recipes are .json and load through the extension's Plugins page)"));
    }
    if name.eq_ignore_ascii_case(REGISTRY_JS) {
        return Err(
            "registry.js is generated; installing over it would break the extension".into(),
        );
    }
    Ok(name)
}

/// Rewrite `registry.js` from the files actually present, atomically.
fn regenerate(local: &Path) -> Result<Vec<String>, String> {
    let scripts = list_scripts(local)?;
    let mut out = String::from(REGISTRY_HEADER);
    for (i, file) in scripts.iter().enumerate() {
        let ident = import_ident(file, i);
        out.push_str(&format!("import * as {ident} from \"./{file}\";\n"));
    }
    out.push_str("\nexport const SCRIPTS = [");
    for (i, file) in scripts.iter().enumerate() {
        if i > 0 {
            out.push_str(", ");
        }
        let ident = import_ident(file, i);
        out.push_str(&format!("{{ file: \"{file}\", mod: {ident} }}"));
    }
    out.push_str("];\n");
    let target = local.join(REGISTRY_JS);
    crate::util::atomic_write(&target, out.as_bytes())
        .map_err(|e| format!("{}: {e}", target.display()))?;
    Ok(scripts)
}

/// Every `*.js` in `hosts/local/` except the registry itself, sorted so the
/// generated file is stable across regenerations.
fn list_scripts(local: &Path) -> Result<Vec<String>, String> {
    let mut scripts = Vec::new();
    for entry in std::fs::read_dir(local).map_err(|e| format!("{}: {e}", local.display()))? {
        let entry = entry.map_err(|e| e.to_string())?;
        let name = entry.file_name().to_string_lossy().into_owned();
        if !name.to_ascii_lowercase().ends_with(".js") || name.eq_ignore_ascii_case(REGISTRY_JS) {
            continue;
        }
        if entry.path().is_file() {
            scripts.push(name);
        }
    }
    scripts.sort();
    Ok(scripts)
}

/// A valid, unique JS identifier for one import binding.
fn import_ident(file: &str, index: usize) -> String {
    let mut ident = String::from("p");
    for ch in file.chars() {
        if ch.is_ascii_alphanumeric() || ch == '_' {
            ident.push(ch);
        } else {
            ident.push('_');
        }
    }
    // Identifiers cannot start with a digit and "p" already guarantees a
    // letter head; the index disambiguates files that sanitize to the same
    // name (`a b.js` vs `a-b.js`).
    format!("{ident}_{index}")
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn temp_ext(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "ripdl-extplug-{tag}-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_millis()
        ));
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn install_generates_a_working_registry() {
        let ext = temp_ext("install");
        let body = b"export default { match() { return null; } };";
        let msg = install(&ext, "my host.js", body).unwrap();
        assert!(msg.starts_with("my host.js"), "{msg}");

        let registry =
            std::fs::read_to_string(ext.join("hosts").join("local").join("registry.js")).unwrap();
        assert!(
            registry.contains("import * as pmy_host_js_0 from \"./my host.js\";"),
            "{registry}"
        );
        assert!(
            registry.contains(r#"{ file: "my host.js", mod: pmy_host_js_0 }"#),
            "{registry}"
        );
        // Second plugin: both listed, unique bindings, sorted order.
        install(&ext, "second.js", b"export default {};").unwrap();
        let registry =
            std::fs::read_to_string(ext.join("hosts").join("local").join("registry.js")).unwrap();
        assert!(registry.contains("./my host.js"));
        assert!(registry.contains("./second.js"));
        assert!(
            registry.contains("pmy_host_js_0") && registry.contains("psecond_js_1"),
            "{registry}"
        );
        let _ = std::fs::remove_dir_all(&ext);
    }

    #[test]
    fn uninstall_updates_the_registry() {
        let ext = temp_ext("uninstall");
        install(&ext, "a.js", b"export default {};").unwrap();
        install(&ext, "b.js", b"export default {};").unwrap();
        uninstall(&ext, "a.js").unwrap();
        let registry =
            std::fs::read_to_string(ext.join("hosts").join("local").join("registry.js")).unwrap();
        assert!(!registry.contains("./a.js"), "{registry}");
        assert!(registry.contains("./b.js"));
        assert_eq!(installed(&ext), vec!["b.js".to_string()]);
        let _ = std::fs::remove_dir_all(&ext);
    }

    #[test]
    fn bad_names_and_the_registry_are_refused() {
        let ext = temp_ext("names");
        // A path, not a file name: only the component is used...
        assert_eq!(
            install(&ext, "C:\\evil\\x.js", b"export default {};").unwrap(),
            "x.js (registry now lists 1)"
        );
        // ...but the registry itself and non-scripts are refused.
        assert!(install(&ext, "registry.js", b"x").is_err());
        assert!(install(&ext, "plugin.json", b"{}").is_err());
        assert!(install(&ext, "", b"x").is_err());
        assert!(uninstall(&ext, "registry.js").is_err());
        // A non-.js file already sitting in hosts/local/ is never listed.
        std::fs::write(ext.join("hosts").join("local").join("notes.txt"), "hi").unwrap();
        assert_eq!(installed(&ext), vec!["x.js".to_string()]);
        let _ = std::fs::remove_dir_all(&ext);
    }

    #[test]
    fn folder_version_reads_a_jsonc_manifest() {
        let ext = temp_ext("version");
        assert_eq!(folder_version(&ext), None);
        std::fs::write(
            ext.join("manifest.json"),
            "// header comment\n{\n  // inner comment\n  \"version\": \"0.4.1\"\n}\n",
        )
        .unwrap();
        assert_eq!(folder_version(&ext), Some("0.4.1".to_string()));
        let _ = std::fs::remove_dir_all(&ext);
    }

    #[test]
    fn managed_update_replaces_bundle_and_preserves_user_scripts() {
        let source = temp_ext("managed-source");
        let managed = temp_ext("managed-target").join("extension");
        std::fs::write(source.join("manifest.json"), r#"{"version":"0.5.0"}"#).unwrap();
        std::fs::write(source.join("background.js"), "new worker").unwrap();
        std::fs::create_dir_all(source.join("hosts/local")).unwrap();
        std::fs::write(source.join("hosts/local/registry.js"), "stale registry").unwrap();
        std::fs::create_dir_all(&managed).unwrap();
        std::fs::write(managed.join("manifest.json"), r#"{"version":"0.4.0"}"#).unwrap();
        std::fs::write(managed.join("obsolete.js"), "old file").unwrap();
        std::fs::create_dir_all(managed.join("hosts/local")).unwrap();
        std::fs::write(managed.join("hosts/local/my-host.js"), "export default {};").unwrap();
        std::fs::write(managed.join("hosts/local/registry.js"), "old registry").unwrap();

        let result = sync_managed(&source, &managed).unwrap();

        assert!(result.updated);
        assert_eq!(result.version, "0.5.0");
        assert_eq!(result.plugins, vec!["my-host.js"]);
        assert!(managed.join("background.js").is_file());
        assert!(!managed.join("obsolete.js").exists());
        let registry = std::fs::read_to_string(managed.join("hosts/local/registry.js")).unwrap();
        assert!(registry.contains("./my-host.js"));
        assert!(!registry.contains("stale registry"));

        let _ = std::fs::remove_dir_all(source);
        if let Some(parent) = managed.parent() {
            let _ = std::fs::remove_dir_all(parent);
        }
    }

    #[cfg(debug_assertions)]
    #[test]
    fn managed_debug_sync_refreshes_equal_version_bundle_files() {
        let source = temp_ext("managed-debug-source");
        let managed = temp_ext("managed-debug-target").join("extension");
        std::fs::write(source.join("manifest.json"), r#"{"version":"0.4.1"}"#).unwrap();
        std::fs::write(source.join("background.js"), "new source worker").unwrap();
        std::fs::create_dir_all(source.join("hosts/local")).unwrap();
        std::fs::write(source.join("hosts/local/registry.js"), "source registry").unwrap();
        std::fs::create_dir_all(managed.join("hosts/local")).unwrap();
        std::fs::write(managed.join("manifest.json"), r#"{"version":"0.4.1"}"#).unwrap();
        std::fs::write(managed.join("background.js"), "old worker").unwrap();
        std::fs::write(managed.join("hosts/local/user.js"), "export default {};").unwrap();

        let result = sync_managed(&source, &managed).unwrap();

        assert!(result.updated);
        assert_eq!(
            std::fs::read_to_string(managed.join("background.js")).unwrap(),
            "new source worker"
        );
        assert_eq!(result.plugins, vec!["user.js"]);
        let _ = std::fs::remove_dir_all(source);
        if let Some(parent) = managed.parent() {
            let _ = std::fs::remove_dir_all(parent);
        }
    }

    #[test]
    fn sync_relists_scripts_after_a_registry_reset() {
        let ext = temp_ext("sync");
        // The shipped registry (lists nothing) replaced the user's one.
        let local = ext.join("hosts").join("local");
        std::fs::create_dir_all(&local).unwrap();
        std::fs::write(local.join("registry.js"), "export const SCRIPTS = [];\n").unwrap();
        std::fs::write(local.join("kept.js"), "export default {};").unwrap();

        // No manifest: refused, and nothing is written.
        assert!(sync(&ext).is_err());
        assert!(!ext.join("manifest.json").exists());

        std::fs::write(ext.join("manifest.json"), "{\"version\":\"0.4.1\"}").unwrap();
        assert_eq!(sync(&ext).unwrap(), vec!["kept.js".to_string()]);
        let registry = std::fs::read_to_string(local.join("registry.js")).unwrap();
        assert!(registry.contains("./kept.js"), "{registry}");
        let _ = std::fs::remove_dir_all(&ext);
    }
}
